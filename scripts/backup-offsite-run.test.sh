#!/usr/bin/env sh
# Regression tests for scripts/backup-offsite-run.sh.
#
# No network, no B2, no GPG and no real dump. The uploader is replaced by a
# stub that records its exact argument vector, so the tests can assert both
# behaviour and credential hygiene: that credentials are referenced by path and
# never placed in argv, and that the dump is always named explicitly rather
# than discovered.
#
# Run: sh scripts/backup-offsite-run.test.sh
# Exits non-zero if any test fails.

set -eu

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_dir=$(CDPATH= cd -- "$script_dir/.." && pwd)
offsite_script="$repo_dir/scripts/backup-offsite-run.sh"
manifest_script="$repo_dir/scripts/backup-manifest.sh"
# Strip any trailing separator so recorded paths have exactly one slash;
# assertions below compare argument values literally.
tmpbase=${TMPDIR:-/tmp}
tmpbase=${tmpbase%/}
work=$(mktemp -d "$tmpbase/libris-offsite-test.XXXXXX")

pass=0
fail=0
RC=0

cleanup() { rm -rf "$work"; }
trap cleanup EXIT HUP INT TERM

ok() {
  pass=$((pass + 1))
  echo "  ok   - $1"
}

no() {
  fail=$((fail + 1))
  echo "  FAIL - $1"
  [ $# -gt 1 ] && echo "         $2"
  return 0
}

# A uploader stub. Records argv one per line, touches the status file the way
# the real uploader does (merging only the "offsite" key), and exits with the
# requested code.
make_uploader_stub() {
  mkdir -p "$work/bin"
  cat > "$work/bin/uploader" <<'STUB'
#!/usr/bin/env sh
: > "${UPLOADER_ARGV_LOG:?}"
for a in "$@"; do
  printf '%s\n' "$a" >> "$UPLOADER_ARGV_LOG"
done
# Mirror the real uploader: merge an offsite result without disturbing the
# local status keys.
status=""
prefix=""
while [ $# -gt 0 ]; do
  case "$1" in
    --status-file) status=$2; shift 2 ;;
    --prefix) prefix=$2; shift 2 ;;
    --dump-file) dump=$2; shift 2 ;;
    *) shift ;;
  esac
done
if [ "${UPLOADER_EXIT:-0}" = "0" ]; then
  [ -n "$status" ] && printf '  "offsite": {\n    "status": "ok",\n    "object": "%s%s.gpg"\n  }\n' \
    "$prefix" "$(basename -- "$dump" .gpg)" >> "$status"
  exit 0
fi
[ -n "$status" ] && printf '  "offsite": {\n    "status": "failed",\n    "error": "stubbed failure"\n  }\n' >> "$status"
exit 1
STUB
  chmod +x "$work/bin/uploader"
}

# Build a valid backup directory: a real gzip dump, a real manifest generated by
# backup-manifest.sh, and a local status file reporting success.
setup_valid_backup() {
  rm -rf "$work/backup"
  mkdir -p "$work/backup"
  dump="$work/backup/libris-20261019T050000Z.sql.gz"
  printf 'CREATE TABLE t (id INT);\nINSERT INTO t VALUES (1);\n' > "$work/payload.sql"
  gzip -9 "$work/payload.sql"
  mv "$work/payload.sql.gz" "$dump"
  sh "$manifest_script" "$dump" "$dump.manifest.json" >/dev/null
  cat > "$work/backup/last-run.status" <<'JSON'
{
  "status": "ok",
  "started_utc": "2026-10-19T05:00:00Z",
  "dump": "libris-20261019T050000Z.sql.gz",
  "offsite": "not_configured"
}
JSON
}

# STUB_EXIT selects the uploader stub's exit code for the next call. The knobs
# are exported for the duration of the invocation rather than applied as a
# `VAR=x function` prefix, because that prefix is not portable in POSIX sh and
# would otherwise be passed to the script as a positional argument instead.
STUB_EXIT=0
run_offsite() {
  set +e
  rm -f "$work/last-arglog"
  LIBRIS_BACKUP_DIR="$work/backup" \
  LIBRIS_B2_CREDENTIALS="$work/creds" \
  LIBRIS_OFFSITE_UPLOADER="$work/bin/uploader" \
  LIBRIS_GPG_HOME="$work/gnupg" \
  UPLOADER_ARGV_LOG="$work/bin/uploader.arglog" \
  UPLOADER_EXIT="$STUB_EXIT" \
    sh "$offsite_script" "$@" >"$work/stdout" 2>"$work/stderr"
  RC=$?
  set -e
  # Preserve this invocation's stdout and recorded argv for the assertions
  # that follow, then clear them so the next call starts from a known state.
  cp "$work/stdout" "$work/last-stdout"
  cp "$work/stderr" "$work/last-stderr"
  cp "$work/bin/uploader.arglog" "$work/last-arglog" 2>/dev/null || :
  rm -f "$work/bin/uploader.arglog"
}

make_uploader_stub
printf 'keyID=synthetic0000\napplicationKey=synthetic-secret\n' > "$work/creds"
chmod 600 "$work/creds"

echo "offsite integration:"

# 1. A dump argument is required.
run_offsite
if [ "$RC" -eq 1 ] && grep -q "usage:" "$work/last-stdout"; then
  ok "a missing dump argument is refused"
else
  no "a missing dump argument is refused" "rc=$RC"
fi

# 2. Nothing but a .sql.gz artifact may be transferred.
setup_valid_backup
run_offsite "$work/backup/last-run.status"
if [ "$RC" -eq 1 ] && grep -q "\.sql\.gz artifact" "$work/last-stdout"; then
  ok "a non-.sql.gz argument is refused"
else
  no "a non-.sql.gz argument is refused" "rc=$RC"
fi

# 2b. The credential file must be named explicitly. A defaulted path would let
#     a misconfigured run transfer with whatever key last occupied it.
setup_valid_backup
set +e
LIBRIS_BACKUP_DIR="$work/backup" \
LIBRIS_OFFSITE_UPLOADER="$work/bin/uploader" \
  sh "$offsite_script" "$work/backup/libris-20261019T050000Z.sql.gz" \
  >"$work/stdout" 2>"$work/stderr"
RC=$?
set -e
if [ "$RC" -eq 1 ] && grep -q "must name the B2 credential file explicitly" "$work/stdout"; then
  ok "an unnamed credential file is refused"
else
  no "an unnamed credential file is refused" "rc=$RC"
fi

# 2c. A missing credential file is refused before anything is transferred.
setup_valid_backup
set +e
LIBRIS_BACKUP_DIR="$work/backup" \
LIBRIS_B2_CREDENTIALS="$work/no-such-creds" \
LIBRIS_OFFSITE_UPLOADER="$work/bin/uploader" \
  sh "$offsite_script" "$work/backup/libris-20261019T050000Z.sql.gz" \
  >"$work/stdout" 2>"$work/stderr"
RC=$?
set -e
if [ "$RC" -eq 1 ] && grep -q "credentials" "$work/stdout"; then
  ok "a missing credential file is refused"
else
  no "a missing credential file is refused" "rc=$RC"
fi

# 2d. A missing uploader is refused rather than silently skipped.
setup_valid_backup
set +e
LIBRIS_BACKUP_DIR="$work/backup" \
LIBRIS_B2_CREDENTIALS="$work/creds" \
LIBRIS_OFFSITE_UPLOADER="$work/bin/no-such-uploader" \
  sh "$offsite_script" "$work/backup/libris-20261019T050000Z.sql.gz" \
  >"$work/stdout" 2>"$work/stderr"
RC=$?
set -e
if [ "$RC" -eq 1 ] && grep -q "uploader" "$work/stdout"; then
  ok "a missing uploader is refused"
else
  no "a missing uploader is refused" "rc=$RC"
fi

# 3. The dump must live in the backup directory: this is what stops a synthetic
#    canary fixture, or any other file, from being uploaded in production.
outside=$(mktemp -d "${TMPDIR:-/tmp}/libris-outside.XXXXXX")
cp "$work/backup/libris-20261019T050000Z.sql.gz" "$outside/canary.sql.gz"
run_offsite "$outside/canary.sql.gz"
if [ "$RC" -eq 1 ] && grep -q "outside the backup directory" "$work/stdout"; then
  ok "a dump outside the backup directory is refused"
else
  no "a dump outside the backup directory is refused" "rc=$RC"
fi
rm -rf "$outside"

# 4. With no recorded local success there is no evidence the dump is complete.
setup_valid_backup
mv "$work/backup/last-run.status" "$work/backup/status.bak"
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
if [ "$RC" -eq 1 ]; then
  ok "a missing local status file refuses the transfer"
else
  no "a missing local status file refuses the transfer" "rc=$RC"
fi
mv "$work/backup/status.bak" "$work/backup/last-run.status"

# 5. A failed local run must never be uploaded.
sed 's/"status": "ok"/"status": "failed"/' "$work/backup/last-run.status" \
  > "$work/backup/status.new" && mv "$work/backup/status.new" "$work/backup/last-run.status"
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
if [ "$RC" -eq 1 ] && grep -q "not 'ok'" "$work/stdout"; then
  ok "a locally failed backup is not transferred"
else
  no "a locally failed backup is not transferred" "rc=$RC"
fi
setup_valid_backup

# 6. A corrupt archive is refused rather than uploaded.
setup_valid_backup
printf 'not a gzip stream' > "$work/backup/libris-20261019T050000Z.sql.gz"
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
if [ "$RC" -eq 1 ] && grep -q "gzip integrity" "$work/stdout"; then
  ok "a dump failing its gzip integrity check is refused"
else
  no "a dump failing its gzip integrity check is refused" "rc=$RC"
fi
setup_valid_backup

# 7. A missing manifest means nothing describes the artifact.
setup_valid_backup
rm -f "$work/backup/libris-20261019T050000Z.sql.gz.manifest.json"
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
if [ "$RC" -eq 1 ] && grep -q "manifest" "$work/stdout"; then
  ok "a missing manifest refuses the transfer"
else
  no "a missing manifest refuses the transfer" "rc=$RC"
fi
setup_valid_backup

# 8. An artifact that no longer matches its manifest is refused. This is the
#    guard against a truncated or swapped dump being uploaded.
setup_valid_backup
printf 'CREATE TABLE other (id INT);\n' > "$work/payload2.sql"
gzip -9 "$work/payload2.sql"
cp "$work/payload2.sql.gz" "$work/backup/libris-20261019T050000Z.sql.gz"
rm -f "$work/payload2.sql.gz"
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
if [ "$RC" -eq 1 ] && grep -q "does not match the sha256" "$work/stdout"; then
  ok "a dump that disagrees with its manifest is refused"
else
  no "a dump that disagrees with its manifest is refused" "rc=$RC"
fi
setup_valid_backup

# 9. The happy path invokes the uploader exactly once, naming the dump
#    explicitly and pinning the bucket, prefix and credentials by path.
STUB_EXIT=0
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
arglog="$work/last-arglog"
if [ "$RC" -eq 0 ] &&
  grep -qx -- "--dump-file" "$arglog" &&
  grep -qx -- "$work/backup/libris-20261019T050000Z.sql.gz" "$arglog" &&
  grep -qx -- "libris-backups" "$arglog" &&
  grep -qx -- "38fd5596187d47ffa5110c1d" "$arglog" &&
  grep -qx -- "backups/" "$arglog" &&
  grep -qx -- "$work/creds" "$arglog" &&
  grep -qx -- "--failure-file" "$arglog" &&
  grep -qx -- "$work/backup/LAST_OFFSITE_FAILURE" "$arglog"
then
  ok "a valid dump is transferred with explicit, pinned arguments"
else
  no "a valid dump is transferred with explicit, pinned arguments" "rc=$RC"
fi

# 9b. A caller that spells the backup directory with a redundant separator
#     still refers to the same directory, and must not be mistaken for a path
#     outside the backup directory.
setup_valid_backup
STUB_EXIT=0
LIBRIS_BACKUP_DIR_DOUBLE_SLASH=1
run_offsite_slashed() {
  set +e
  rm -f "$work/last-arglog"
  LIBRIS_BACKUP_DIR="$work/backup//" \
  LIBRIS_B2_CREDENTIALS="$work/creds" \
  LIBRIS_OFFSITE_UPLOADER="$work/bin/uploader" \
  LIBRIS_GPG_HOME="$work/gnupg" \
  UPLOADER_ARGV_LOG="$work/bin/uploader.arglog" \
  UPLOADER_EXIT=0 \
    sh "$offsite_script" "$@" >"$work/stdout" 2>"$work/stderr"
  RC=$?
  set -e
  cp "$work/stdout" "$work/last-stdout"
  cp "$work/bin/uploader.arglog" "$work/last-arglog" 2>/dev/null || :
  rm -f "$work/bin/uploader.arglog"
}
run_offsite_slashed "$work/backup/libris-20261019T050000Z.sql.gz"
if [ "$RC" -eq 0 ] && ! grep -q "outside the backup directory" "$work/last-stdout"; then
  ok "a backup directory spelled with a redundant slash is handled"
else
  no "a backup directory spelled with a redundant slash is handled" "rc=$RC"
fi

# 10. The secret must never reach argv.
if ! grep -q "synthetic-secret" "$arglog"; then
  ok "the application key secret is never passed in argv"
else
  no "the application key secret is never passed in argv" "secret found in argv"
fi

# 11. Re-running the same dump is a no-op, so a retried service start cannot
#     upload the same object twice.
setup_valid_backup
STUB_EXIT=0
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
# Copy, do not alias: the next run_offsite clears $work/last-arglog.
first_arglog="$work/first-arglog"
cp "$work/last-arglog" "$first_arglog" 2>/dev/null || :
STUB_EXIT=0
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
if [ "$RC" -eq 0 ] && grep -q "already transferred" "$work/last-stdout" &&
  [ ! -s "$work/last-arglog" ] && [ -s "$first_arglog" ]; then
  ok "re-transferring the same dump is a no-op"
else
  no "re-transferring the same dump is a no-op" "rc=$RC"
fi

# 12. A transfer failure is reported as exit 20, distinctly from a backup fault.
setup_valid_backup
STUB_EXIT=1
run_offsite "$work/backup/libris-20261019T050000Z.sql.gz"
if [ "$RC" -eq 20 ]; then
  ok "a failed transfer exits 20, distinct from a backup fault"
else
  no "a failed transfer exits 20, distinct from a backup fault" "rc=$RC"
fi

# 13. A failed transfer must leave the local backup entirely intact.
if [ -f "$work/backup/libris-20261019T050000Z.sql.gz" ] &&
  [ -f "$work/backup/libris-20261019T050000Z.sql.gz.manifest.json" ] &&
  grep -q '"status": "ok"' "$work/backup/last-run.status" &&
  grep -q '"offsite"' "$work/backup/last-run.status"; then
  ok "a failed transfer preserves the dump, manifest and local success status"
else
  no "a failed transfer preserves the dump, manifest and local success status" "local artifacts changed"
fi

# 14. The status file must never report success for a failed offsite stage.
if grep -q '"status": "failed"' "$work/backup/last-run.status"; then
  ok "a failed transfer is recorded in the status file as a failure"
else
  no "a failed transfer is recorded in the status file as a failure" "no failed offsite status"
fi

# 15. A failed transfer must never print a success line: the caller's log is
#     the first place an operator would look.
if ! grep -q "verified" "$work/last-stdout" && grep -q "FAILED" "$work/last-stdout"; then
  ok "a failed transfer never reports success"
else
  no "a failed transfer never reports success" "stdout claimed success"
fi

# 16. The dump's own bytes are untouched by a failed transfer.
dump_now=$(sha256sum "$work/backup/libris-20261019T050000Z.sql.gz" | awk '{print $1}')
manifest_now=$(sed -n 's/.*"sha256": *"\([a-f0-9]*\)".*/\1/p' \
  "$work/backup/libris-20261019T050000Z.sql.gz.manifest.json" | head -1)
if [ "$dump_now" = "$manifest_now" ]; then
  ok "the local artifact is byte-identical to what its manifest describes"
else
  no "the local artifact is byte-identical to what its manifest describes" "sha mismatch after failure"
fi

echo "passed: $pass  failed: $fail"
[ "$fail" -eq 0 ]